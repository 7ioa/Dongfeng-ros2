class Mesh:
    def __init__(self):self.v=[];self.f=[]
    def add(self,v,f):
        k=len(self.v);self.v.extend(tuple(float(x) for x in p) for p in v)
        self.f.extend(tuple(k+i for i in t) for t in f)
    def quad(self,p):self.add(p,[(0,1,2),(0,2,3)])
    def arrays(self):
        v=np.asarray(self.v,dtype=np.float32);f=np.asarray(self.f,dtype=np.uint32)
        n=np.zeros_like(v);cross=np.cross(v[f[:,1]]-v[f[:,0]],v[f[:,2]]-v[f[:,0]])
        for j in range(3):np.add.at(n,f[:,j],cross)
        n/=np.maximum(np.linalg.norm(n,axis=1),1e-15)[:,None]
        return v,f,n
