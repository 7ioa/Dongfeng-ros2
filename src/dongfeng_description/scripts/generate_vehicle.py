def elem(parent,tag,**attrs):return ET.SubElement(parent,tag,{k:str(v) for k,v in attrs.items()})
def xyz(v):return ' '.join(f'{a:.9g}' for a in v)
def origin(parent,position=(0,0,0),rpy=(0,0,0)):elem(parent,'origin',xyz=xyz(position),rpy=xyz(rpy))
def inertial(link,mass,size,position=(0,0,0),cylinder=False):
    node=elem(link,'inertial');origin(node,position);elem(node,'mass',value=mass)
    if cylinder:
        r,w=size;ix=mass*(3*r*r+w*w)/12;iy=mass*r*r/2;iz=ix
    else:
        x,y,z=size;ix=mass*(y*y+z*z)/12;iy=mass*(x*x+z*z)/12;iz=mass*(x*x+y*y)/12
    elem(node,'inertia',ixx=ix,ixy=0,ixz=0,iyy=iy,iyz=0,izz=iz)
