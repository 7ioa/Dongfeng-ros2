def area(p):return sum(p[i][0]*p[(i+1)%len(p)][1]-p[(i+1)%len(p)][0]*p[i][1] for i in range(len(p)))/2

def triangulate(p):
    ids=list(range(len(p)));result=[]
    def cr(a,b,c):return (b[0]-a[0])*(c[1]-a[1])-(b[1]-a[1])*(c[0]-a[0])
    while len(ids)>3:
        for q in range(len(ids)):
            a,b,c=ids[q-1],ids[q],ids[(q+1)%len(ids)]
            if cr(p[a],p[b],p[c])<=1e-14:continue
            if any(min(cr(p[a],p[b],p[j]),cr(p[b],p[c],p[j]),cr(p[c],p[a],p[j]))>=-1e-14 for j in ids if j not in (a,b,c)):continue
            result.append((a,b,c));ids.pop(q);break
        else:raise ValueError('Non-simple polygon')
    result.append(tuple(ids));return result

def rounded(x0,y0,x1,y1,r,n=8):
    points=[]
    for cx,cy,a in [(x1-r,y0+r,-math.pi/2),(x1-r,y1-r,0),(x0+r,y1-r,math.pi/2),(x0+r,y0+r,math.pi)]:
        points.extend((cx+r*math.cos(t),cy+r*math.sin(t)) for t in np.linspace(a,a+math.pi/2,n+1))
    return points

def circle(x,y,r,n=16):return [(x+r*math.cos(t),y+r*math.sin(t)) for t in np.linspace(0,math.tau,n,endpoint=False)]

def prism(points,z,height,part,mat,axes=None):
    p=list(points)
    if area(p)<0:p.reverse()
    faces=triangulate(p);count=len(p)
    v=[(x,y,h) for h in [z,z+height] for x,y in p]
    f=[(c,b,a) for a,b,c in faces]+[(a+count,b+count,c+count) for a,b,c in faces]
    for i in range(count):
        j=(i+1)%count;f.extend([(i,j,j+count),(i,j+count,i+count)])
    if axes is not None:v=[tuple(axes@np.asarray(q)) for q in v]
    bucket(part,mat).add(v,f)

def box(x,y,z,sx,sy,sz,part,mat):
    prism([(x-sx/2,y-sy/2),(x+sx/2,y-sy/2),(x+sx/2,y+sy/2),(x-sx/2,y+sy/2)],z,sz,part,mat)

def beam(a,b,r,part,mat,n=10,r2=None):
    a,b=np.asarray(a,float),np.asarray(b,float);axis=b-a;length=np.linalg.norm(axis)
    if length<1e-10:return
    axis/=length;ref=np.array([0,0,1]) if abs(axis[2])<.9 else np.array([1,0,0])
    u=np.cross(axis,ref);u/=np.linalg.norm(u);v=np.cross(axis,u);r2=r if r2 is None else r2
    pts=[tuple(c+rr*(u*math.cos(t)+v*math.sin(t))) for c,rr in [(a,r),(b,r2)] for t in np.linspace(0,math.tau,n,endpoint=False)]
    faces=[]
    for i in range(n):
        j=(i+1)%n;faces.extend([(i,j,n+j),(i,n+j,n+i)])
    faces.extend((0,i+1,i) for i in range(1,n-1));faces.extend((n,n+i,n+i+1) for i in range(1,n-1))
    bucket(part,mat).add(pts,faces)

def sphere(c,r,part,mat,n=16,rings=8):
    c=np.asarray(c);v=[tuple(c+[0,0,-r])]
    for p in np.linspace(-math.pi/2,math.pi/2,rings+1)[1:-1]:
        v.extend(tuple(c+r*np.array([math.cos(p)*math.cos(t),math.cos(p)*math.sin(t),math.sin(p)])) for t in np.linspace(0,math.tau,n,endpoint=False))
    v.append(tuple(c+[0,0,r]));f=[]
    for j in range(n):f.append((0,1+(j+1)%n,1+j))
    for i in range(rings-2):
        for j in range(n):
            a=1+i*n+j;b=1+i*n+(j+1)%n;f.extend([(a,b,b+n),(a,b+n,a+n)])
    last=1+(rings-2)*n
    for j in range(n):f.append((last+j,last+(j+1)%n,len(v)-1))
    bucket(part,mat).add(v,f)

def tube(points,r,part,mat,n=7):
    # Shared rings keep cable/trim normals smooth, without caps at every segment.
    points=np.asarray(points,float)
    if len(points)<2:return
    closed=np.linalg.norm(points[0]-points[-1])<1e-10
    verts=[];faces=[];previous=None
    for i,p in enumerate(points):
        if closed and i in (0,len(points)-1):tangent=points[1]-points[-2]
        else:tangent=points[min(i+1,len(points)-1)]-points[max(i-1,0)]
        tangent/=np.linalg.norm(tangent)
        if previous is None:
            ref=np.array([0,0,1]) if abs(tangent[2])<.9 else np.array([1,0,0])
            u=np.cross(tangent,ref)
        else:u=previous-tangent*np.dot(previous,tangent)
        u/=np.linalg.norm(u);v=np.cross(tangent,u);previous=u
        verts.extend(tuple(p+r*(u*math.cos(t)+v*math.sin(t))) for t in np.linspace(0,math.tau,n,endpoint=False))
    for i in range(len(points)-1):
        for k in range(n):
            a=i*n+k;b=i*n+(k+1)%n;faces.extend([(a,b,b+n),(a,b+n,a+n)])
    bucket(part,mat).add(verts,faces)
    if not closed:
        for start,reverse in [(0,True),((len(points)-1)*n,False)]:
            cap=[(0,k,k+1) for k in range(1,n-1)]
            if reverse:cap=[(c,b,a) for a,b,c in cap]
            bucket(part,mat).add(verts[start:start+n],cap)

def bezier(p,n=18):
    a,b,c,d=np.asarray(p,float)
    return [(1-t)**3*a+3*(1-t)**2*t*b+3*(1-t)*t*t*c+t**3*d for t in np.linspace(0,1,n)]

def plate_holes(outer,holes,z,thickness,part='base',mat='plate'):
    """Exact polygonal holes using vertical trapezoid decomposition, no booleans."""
    rings=[outer]+holes;edges=[(np.asarray(a),np.asarray(b)) for ring in rings for a,b in zip(ring,ring[1:]+ring[:1]) if abs(a[0]-b[0])>1e-12]
    xs=sorted(set(round(p[0],10) for ring in rings for p in ring))
    def yy(edge,x):
        a,b=edge;return a[1]+(x-a[0])*(b[1]-a[1])/(b[0]-a[0])
    for x0,x1 in zip(xs[:-1],xs[1:]):
        if x1-x0<1e-9:continue
        mid=(x0+x1)/2;hits=[e for e in edges if min(e[0][0],e[1][0])<mid<max(e[0][0],e[1][0])]
        hits.sort(key=lambda e:yy(e,mid));assert len(hits)%2==0
        for low,high in zip(hits[::2],hits[1::2]):
            p=[(x0,yy(low,x0)),(x1,yy(low,x1)),(x1,yy(high,x1)),(x0,yy(high,x0))]
            clean=[]
            for pt in p:
                if not clean or math.dist(pt,clean[-1])>1e-10:clean.append(pt)
            if len(clean)>1 and math.dist(clean[0],clean[-1])<1e-10:clean.pop()
            if len(clean)<3 or area(clean)<1e-14:continue
            f=triangulate(clean)
            bucket(part,mat).add([(x,y,z+thickness) for x,y in clean],f)
            bucket(part,mat).add([(x,y,z) for x,y in clean],[(c,b,a) for a,b,c in f])
    for k,ring in enumerate(rings):
        ring=list(ring)
        if (area(ring)>0)!=(k==0):ring.reverse()
        for a,b in zip(ring,ring[1:]+ring[:1]):
            bucket(part,mat).quad([(*a,z),(*b,z),(*b,z+thickness),(*a,z+thickness)])

def rev_y(profile,part,mat,n=48):
    v=[(r*math.cos(t),y,r*math.sin(t)) for y,r in profile for t in np.linspace(0,math.tau,n,endpoint=False)]
    f=[]
    for i in range(len(profile)):
        j=(i+1)%len(profile)
        for a in range(n):
            b=(a+1)%n;f.extend([(i*n+a,i*n+b,j*n+b),(i*n+a,j*n+b,j*n+a)])
    bucket(part,mat).add(v,[(c,b,a) for a,b,c in f])

